import sys; sys.path.insert(0, sys.argv[0].rsplit('/',1)[0])
from harness import *
import pandas as pd, io
D = sys.argv[0].rsplit('/',1)[0] + '/data/'
at = open_module("Descriptive Analysis")
upload(at, 'da_upload_main', D+'small.csv')
for k,v in [('da_assessor','Panelist'),('da_product','Product'),('da_replicate','Session')]: at.selectbox(key=k).set_value(v).run()
at.number_input(key='da_scale_max').set_value(10).run()
at.button(key='da_run_analysis').click().run(timeout=600)
print('complete', at.session_state['da_analysis_complete'], 'products', sorted(at.session_state['da_summary_df']['Product'].unique()) if 'Product' in at.session_state['da_summary_df'] else at.session_state['da_summary_df'].columns.tolist())
# 1. re-upload different file via real uploader
upload(at, 'da_upload_main', D+'special_levels.csv')
report(at, 'reuploaded special_levels')
ss = at.session_state.to_dict()
print('after reupload: analysis_complete', ss.get('analysis_complete'), 'da_analysis_complete' in ss, 'da_anova_df' in ss)
go(at,'Descriptive',3); report(at,'step3 after reupload')
go(at,'Descriptive',1)
# 2. re-upload file with different column names (mapping persisted)
nf = pd.read_csv(D+'small.csv').rename(columns={'Panelist':'Judge','Product':'Sample','Session':'Rep'})
b = io.StringIO(); nf.to_csv(b, index=False)
upload(at, 'da_upload_main', name='renamed.csv', data=b.getvalue().encode())
report(at,'renamed cols uploaded')
print('  mapping now', at.selectbox(key='da_assessor').value, at.selectbox(key='da_product').value, at.selectbox(key='da_replicate').value)
# 3. run on small, then go to PrefMap/Fusion using DA results
upload(at, 'da_upload_main', D+'small.csv')
for k,v in [('da_assessor','Panelist'),('da_product','Product'),('da_replicate','Session')]: at.selectbox(key=k).set_value(v).run()
at.button(key='da_run_analysis').click().run(timeout=600)
print('DA complete again', at.session_state['da_analysis_complete'])
at.button(key="ui_sidebar_all_modules").click().run()
[b for b in at.button if 'Preference Mapping' in b.label][0].click().run()
at.radio(key="prefmap_sensory_radio").set_value("Use Descriptive Analysis results from this session").run()
report(at, 'prefmap using DA')
print('  prefmap sensory means shape', at.session_state['prefmap_sensory_means'].shape if 'prefmap_sensory_means' in at.session_state and at.session_state['prefmap_sensory_means'] is not None else None)
# go back to DA, change exclusion (reset), come back to prefmap
at.button(key="ui_sidebar_all_modules").click().run()
[b for b in at.button if 'Descriptive Analysis' in b.label][0].click().run()
report(at,'back in DA')
print('  DA still complete after switch?', at.session_state.to_dict().get('da_analysis_complete'), at.session_state['analysis_complete'], 'step', at.session_state['current_step'])
print('  step1 captions:', [c.value[:120] for c in at.caption][:6]); print('  uploader value', at.file_uploader(key='da_upload_main').value)
go(at,'Descriptive',3); report(at,'DA step3 after switch'); go(at,'Descriptive',1)
upload(at, 'da_upload_main', D+'small.csv'); print('  after re-upload same file: da complete', at.session_state.to_dict().get('da_analysis_complete'))
at.multiselect(key='da_exclude_cols').set_value(['Caramel']).run()
print('  after exclude change: da_analysis_complete', at.session_state.to_dict().get('da_analysis_complete'))
at.button(key="ui_sidebar_all_modules").click().run()
[b for b in at.button if 'Preference Mapping' in b.label][0].click().run()
report(at,'prefmap after DA invalidated')
print('  prefmap sensory means still', at.session_state['prefmap_sensory_means'].shape if 'prefmap_sensory_means' in at.session_state and at.session_state['prefmap_sensory_means'] is not None else None)
# Fusion with DA
at.button(key="ui_sidebar_all_modules").click().run()
[b for b in at.button if 'Data Fusion' in b.label][0].click().run()
print('fusion radio options', at.radio(key='fusion_source_radio').options)
report(at,'fusion open')
